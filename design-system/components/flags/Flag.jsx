/** Country Flags — circular/flat country & region flags from the Figma "Country Flags" page. */
export function Flag({ name = 'Indonesia', size = 20, style, ...rest }) {
  const d = flags[name];
  if (!d) return <span style={{ display: 'inline-block', width: size, height: size, borderRadius: 999, background: 'var(--bg-soft-200)', ...style }} />;
  return <svg width={size} height={size} viewBox={d.viewBox} fill="none" aria-label={name} role="img" style={{ display: 'block', flexShrink: 0, ...style }} dangerouslySetInnerHTML={{ __html: d.body }} {...rest} />;
}
